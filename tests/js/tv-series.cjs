const assert = require('node:assert/strict');
const fs = require('node:fs');
const {JSDOM, VirtualConsole} = require('jsdom');

(async () => {
    const errors = [];
    const console = new VirtualConsole();
    console.on('jsdomError', error => errors.push(error));
    console.on('error', error => errors.push(error));
    const dom = new JSDOM('<meta name="csrf-token" content="test"><div id="app"></div>', {url: 'http://localhost/tv-shows', runScripts: 'outside-only', virtualConsole: console});
    try {
        dom.window.eval(fs.readFileSync('public/js/app.js', 'utf8'));
        const requests = [];
        let resolveSave;
        let failSave = false;
        const services = ['netflix', 'prime', 'now', 'disney', 'hbo_max', 'apple_tv', 'paramount_plus', 'bbc_iplayer', 'itvx', 'channel4'].map(key => {const table = {prime: 'amazon', now: 'nowtv', disney: 'disney_plus'}[key] || key; return {key, table, column: 'on_' + table, icon: '/images/' + table + '.png', label: key};});
        const show = {id: 1, imdb_id: 'tt0903747', name: 'Breaking Bad', year: 2008, rating: 9.5, top250_rank: 1, watched: 0, favourite: 0, watchlist: 1, on_netflix: 1, image_url: 'https://example.test/original.jpg', image_url_small_extended: '/storage/tv-shows/test.jpg'};
        dom.window.axios.get = async (url, options) => {
            if (options && options.params.random) return {data: {show: {...show, watched: 0}}};
            if (url === '/tv-shows/watchlist') return {data: show.watchlist ? [{...show}] : []};
            requests.push({url, params: options.params});
            return {data: {data: [{...show}], current_page: 1, last_page: 1, total: 1, services, summary: {watched: show.watched, total: 1, watchlist: show.watchlist}, filters: {genres: ['Drama'], decades: [2000], has_languages: true}}};
        };
        let posts = 0;
        dom.window.axios.post = (url, payload) => {posts++; return failSave ? Promise.reject(new Error('failed')) : new Promise(resolve => {resolveSave = value => {show[payload.field] = Number(payload.value); resolve(value);};});};
        const Component = dom.window.Vue.options.components['tv-series-page'];
        const vm = new Component().$mount();
        dom.window.document.body.appendChild(vm.$el);
        await new Promise(resolve => setImmediate(resolve));
        assert.match(vm.$el.textContent, /Breaking Bad/);
        assert.match(vm.$el.textContent, /Save my score!/);
        assert.equal(vm.$el.querySelector('a.btn-success').getAttribute('href'), '/register');
        assert.match(vm.$el.textContent, /Pick me a random TV show!/);
        assert.equal(requests[0].url, '/tv-shows/catalogue');
        assert.equal(vm.filtersShown, false, 'extra filters are hidden on first entry');
        vm.setFiltersShown(true);
        assert.equal(dom.window.sessionStorage.getItem('catalogue-filters-shown'), 'true');
        const header = vm.$el.querySelector('.card-header');
        assert.equal(header.classList.contains('pl-0'), false, 'guest header retains movie-page padding');
        assert.ok(header.querySelector('#tv-extra-filters > .col-lg-1'), 'guest filters include the movie spacer');
        const favouriteLabel = header.querySelector('#favourites_only_checkbox').closest('label');
        assert.equal(dom.window.getComputedStyle(favouriteLabel).height, '40px', 'guest label height matches movies');
        assert.ok(header.querySelector('#unwatched_only_checkbox').closest('.col-12').classList.contains('col-lg-2'));
        assert.match(header.querySelector('#unwatched_only_checkbox').closest('label').textContent, /Unwatched Only/);
        assert.ok(vm.$el.querySelector('.tv-summary h4').classList.contains('d-inline'));
        assert.equal(dom.window.getComputedStyle(vm.$el.querySelector('.tv-summary > .btn-group')).paddingBottom, '10px', 'random button has the same gap above cards as movies');
        assert.ok(header.querySelector('.tv-title'));
        const topRow = header.querySelector('.tv-filter-form .container > .row');
        assert.equal(topRow.querySelectorAll('.col-lg-3').length, 4, 'title, search, years and genres use the movie header columns');
        assert.equal(topRow.children[1].querySelector('input').placeholder, 'Search');
        assert.equal(topRow.children[2].querySelector('select').id, 'tv-decade');
        assert.equal(topRow.children[3].querySelector('select').id, 'tv-genre');
        const favouriteCheckbox = [...header.querySelectorAll('label')].find(label => label.textContent.includes('Favourites')).querySelector('input');
        assert.match(favouriteCheckbox.previousSibling.textContent, /Favourites/, 'checkbox follows its label like movie filters');
        assert.equal(header.querySelectorAll('.tv-stream-grid input').length, 10);
        assert.equal(vm.$el.querySelectorAll('.tv-platforms .platform').length, 1, 'guest sees available services');
        assert.equal(vm.$el.querySelector('.tv-platforms .netflix').disabled, true);
        await vm.selectServices(true);
        assert.equal(requests.at(-1).params.services.length, 10);
        await vm.selectServices(false);
        assert.equal(requests.at(-1).params.services.length, 0);
        vm.filtersShown = false;
        await dom.window.Vue.nextTick();
        assert.match(header.textContent, /More Filters/);
        assert.equal(header.querySelector('#tv-extra-filters').style.display, 'none');
        vm.filtersShown = true;
        await dom.window.Vue.nextTick();
        assert.ok(vm.$el.querySelector('.movieCard .movieImage'), 'uses the movie poster layout');
        assert.match(vm.$el.querySelector('.movieImage').style.backgroundImage, /storage\/tv-shows\/test.jpg/, 'prefers generated thumbnail');
        vm.$el.querySelector('.movieImage img').dispatchEvent(new dom.window.Event('error'));
        await dom.window.Vue.nextTick();
        assert.match(vm.$el.querySelector('.movieImage').style.backgroundImage, /original.jpg/, 'failed thumbnail falls back to original artwork');
        vm.$set(vm.items[0], 'image_url_small_extended', null);
        await dom.window.Vue.nextTick();
        assert.match(vm.$el.querySelector('.movieImage').style.backgroundImage, /original.jpg/, 'falls back to original artwork');
        assert.ok(vm.$el.querySelector('.rating .fa-star'), 'rating uses the movie star');
        assert.ok(vm.$el.querySelector('.rank .filtered_rank'), 'uses the movie rank badge');
        assert.ok(vm.$el.querySelector('.movieCard .footer'), 'IMDb link is the movie footer');
        assert.ok(vm.$el.querySelector('.watchList'), 'unwatched series has the watchlist overlay');
        assert.equal(vm.$el.querySelector('.col-6'), null, 'uses the movie grid on small screens');
        const first = vm.save(vm.items[0], 'watched');
        await vm.save(vm.items[0], 'watched');
        assert.equal(posts, 1, 'rapid clicks save once');
        resolveSave({data: {saved: true}});
        await first;
        assert.equal(vm.items[0].watched, 1);
        assert.equal(vm.summary.watched, 1);
        assert.equal(vm.summary.watchlist, 1);
        await dom.window.Vue.nextTick();
        assert.ok(vm.$el.querySelector('.movieCard.watched .tickContainer .fa-check'));
        assert.ok(vm.$el.querySelector('.favourite'), 'watched series has the favourite overlay');
        failSave = true;
        await vm.save(vm.items[0], 'favourite');
        assert.equal(vm.items[0].favourite, 0, 'failed save does not change state');
        assert.match(vm.error, /Could not save/);
        vm.search = 'Breaking'; vm.status = 'unwatched';
        await vm.load(1);
        assert.equal(requests.at(-1).params.search, 'Breaking');
        assert.equal(requests.at(-1).params.status, 'unwatched');
        vm.unwatched = true; vm.favourites = true; vm.popular = true; vm.english = true; vm.decade = 2000; vm.genre = 'Drama';
        await vm.load(1);
        assert.equal(requests.at(-1).params.unwatched, 1);
        assert.equal(requests.at(-1).params.english, 1);
        assert.equal(requests.at(-1).params.popular, 1);
        assert.equal(requests.at(-1).params.favourites, 1);
        assert.equal(requests.at(-1).params.decade, 2000);
        await vm.openWatchlist();
        await dom.window.Vue.nextTick();
        assert.ok(vm.$el.querySelector('[role="dialog"]'));
        assert.equal(vm.watchlistItems.length, 1, 'watchlist loads independently of active filters');
        vm.closeWatchlist();
        await vm.resetFilters();
        assert.equal(vm.favourites, false);
        assert.equal(vm.popular, false);
        vm.availableFilters.has_languages = false;
        await dom.window.Vue.nextTick();
        assert.match(header.textContent, /English Only/);
        assert.match(header.textContent, /Popular Only/);
        assert.equal(vm.unwatched, false);
        assert.equal(vm.genre, '');
        await vm.pickShow();
        await dom.window.Vue.nextTick();
        assert.ok(vm.$el.querySelector('[aria-labelledby="tv-random-title"]'));
        assert.match(vm.$el.querySelector('[aria-labelledby="tv-random-title"]').textContent, /Breaking Bad/);
        assert.match(vm.$el.querySelector('[aria-labelledby="tv-random-title"]').textContent, /Remove from Watch List/);
        vm.closeRandom();
        const previousGet = dom.window.axios.get;
        dom.window.axios.get = async () => ({data: {show: null}});
        await vm.pickShow();
        await dom.window.Vue.nextTick();
        assert.match(vm.$el.querySelector('[aria-labelledby="tv-random-title"]').textContent, /No unwatched TV shows/);
        vm.closeRandom();
        dom.window.axios.get = previousGet;
        dom.window.axios.get = async (url, options) => {
            const page = options.params.page;
            const start = (page - 1) * 100 + 1;
            return {data: {data: Array.from({length: page === 3 ? 5 : 100}, (_, index) => ({...show, id: start + index, top250_rank: start + index})), current_page: page, last_page: 3, total: 205}};
        };
        await vm.load(1);
        assert.equal(vm.items.length, 100);
        await dom.window.Vue.nextTick();
        assert.match(vm.$el.querySelector('.tv-summary h4').textContent, /of 100 TV shows/);
        assert.match(vm.$el.textContent, /Show more TV shows/);
        await vm.showMore();
        assert.equal(vm.items.length, 200);
        await dom.window.Vue.nextTick();
        assert.match(vm.$el.querySelector('.tv-summary h4').textContent, /of 200 TV shows/);
        assert.equal(vm.items[0].id, 1, 'existing cards remain after loading more');
        assert.equal(vm.items[199].id, 200);
        await vm.refresh();
        assert.equal(vm.items.length, 200, 'saving or refreshing retains all loaded batches');
        await vm.showMore();
        assert.equal(vm.items.length, 205);
        await dom.window.Vue.nextTick();
        assert.equal(vm.$el.querySelector('.tv-show-more'), null, 'button disappears after final batch');
        assert.equal(vm.$el.querySelectorAll('.filtered_rank')[200].textContent, '201');
        await vm.load(1);
        assert.equal(vm.items.length, 100, 'changing filters resets to the first batch');
        dom.window.axios.get = previousGet;
        const member = new Component({propsData: {authenticated: true}}).$mount();
        await new Promise(resolve => setImmediate(resolve));
        assert.doesNotMatch(member.$el.textContent, /Save my score!/);
        assert.ok(member.$el.querySelector('.card-header').classList.contains('pl-0'), 'member header matches movie member padding');
        dom.window.document.body.appendChild(member.$el);
        assert.equal(member.$el.querySelector('#tv-extra-filters > .col-lg-1'), null);
        assert.equal(dom.window.getComputedStyle(member.$el.querySelector('#favourites_only_checkbox').closest('label')).height, '30px');
        assert.ok(member.$el.querySelector('#unwatched_only_checkbox').closest('.col-12').classList.contains('col-lg-3'));
        assert.match(member.$el.querySelector('#unwatched_only_checkbox').closest('label').textContent, /Unwatched By Me/);
        assert.equal(member.$el.querySelector('.tv-summary h4').classList.contains('d-inline'), false);
        member.$destroy();
        assert.deepEqual(errors, []);
        vm.$destroy();
        process.stdout.write('TV shows production bundle checks passed.\n');
    } finally {dom.window.close();}
})().catch(error => {console.error(error); process.exitCode = 1;});
